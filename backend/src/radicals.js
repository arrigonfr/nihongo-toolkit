export function enrichRadicals(radicals) {
  if (!Array.isArray(radicals)) return [];
  return radicals.map((item) => {
    const entry = Number.isInteger(item?.value) ? RADICALS_214[item.value] : null;
    if (!entry) return item;
    const [character, name, meaning] = entry;
    return { ...item, character, name, meaning };
  });
}

function cleanMeaning(value) {
  if (!value) return "";
  return value.replace(/\s*radical\s*\(no\.?\s*\d+\)?/i, "").replace(/^radical number \d+$/i, "").trim();
}

export function extractComponents(character, svg, lookupKanji) {
  if (!svg) return [];
  const seen = new Set([character]);
  const components = [];
  for (const match of svg.matchAll(/<g\b([^>]*)>/g)) {
    const attrs = match[1];
    const element = attrs.match(/kvg:element="([^"]+)"/)?.[1];
    const original = attrs.match(/kvg:original="([^"]+)"/)?.[1];
    const overlay = COMPONENT_OVERLAY[element] || COMPONENT_OVERLAY[original];
    const primary = overlay?.character || element || original;
    if (!primary || seen.has(primary) || [...primary].length !== 1) continue;
    const code = primary.codePointAt(0);
    if (code >= 0x31c0 && code <= 0x31ef) continue;
    seen.add(primary);
    const radicalInfo = RADICAL_BY_CHAR.get(primary) || (original ? RADICAL_BY_CHAR.get(original) : null);
    const record = lookupKanji?.(primary) || (original ? lookupKanji?.(original) : null);
    const meaning = overlay?.meaning || radicalInfo?.meaning || cleanMeaning(record?.meanings?.[0]);
    const name = overlay?.name || radicalInfo?.name || record?.radical_names?.[0];
    const base = overlay?.original || (original && original !== primary && [...original].length === 1 && original !== "つ" ? original : undefined);
    components.push({
      character: primary,
      ...(base ? { original: base } : {}),
      ...(name ? { name } : {}),
      ...(meaning ? { meaning } : {})
    });
  }
  return components;
}
